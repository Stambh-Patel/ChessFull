function table(type: PieceType): number[] {
  switch (type) {
    case 'PAWN': return PAWN;
    case 'KNIGHT': return KNIGHT;
    case 'BISHOP': return BISHOP;
    case 'ROOK': return ROOK;
    case 'QUEEN': return QUEEN;
    case 'KING': return KING_MIDDLEGAME;
  }
}

/** Positional bonus (centipawns) for a WHITE piece of the given type on (row, col). */
export function whiteBonus(type: PieceType, row: number, col: number): number {
  return table(type)[row * 8 + col];
}

/** Positional bonus for a BLACK piece: same table, mirrored vertically. */
export function blackBonus(type: PieceType, row: number, col: number): number {
  const mirroredRow = 7 - row;
  return table(type)[mirroredRow * 8 + col];
}
